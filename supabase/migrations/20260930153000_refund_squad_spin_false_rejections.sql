-- Squad Spin rejected correctly-typed surnames of valid answers: the alias
-- release feeding squad_spin_player_aliases has no surname form for ~40% of
-- players (and none for compound surnames like "Funes Mori"), so a player who
-- typed the surname the reveal itself then showed lost their pot. The resolver
-- now matches name forms directly; this migration refunds every pot lost to a
-- false rejection before the fix.
--
-- The refund set was computed by replaying every wrong-answer event's
-- submitted_text through the FIXED resolveSquadSpinAnswer (exact semantics:
-- name suffixes en+ka, Turkish ı/ß folding, length-gated typo tolerance)
-- against the combo's valid answers — SQL cannot reproduce the resolver, so
-- the accepted event ids are pinned below. The set is closed: post-fix, such
-- an event can no longer be recorded as wrong. Refunds credit the fair pot at
-- the moment of rejection (slightly above the cash-out value, which applies
-- the house margin) — intentionally generous. Re-running is a no-op via the
-- squad_spin_refund idempotency ledger index; on databases without these
-- events (staging) this is a no-op.

