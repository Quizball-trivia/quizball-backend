-- Club leaderboards: users.favorite_club is free text ("Real Madrid", "Real Madrid CF", "Lyon", "Olympique Lyonnais"),
-- so boards group players by a canonical club id (the web catalogue id, src/data/clubs.json). Every catalogue
-- value/label and every legacy spelling found on prod/staging maps here; hidden catalogue duplicates of a public club
-- (wl-lyon, Internazionale...) point at the public id. Owner-restricted clubs are left out, so they never get a board.
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '60s';

CREATE TABLE IF NOT EXISTS public.leaderboard_club_aliases (
  alias text PRIMARY KEY,
  club_id text NOT NULL,
  CONSTRAINT chk_leaderboard_club_aliases_alias CHECK (alias = lower(btrim(alias)) AND alias <> ''),
  CONSTRAINT chk_leaderboard_club_aliases_club_id CHECK (club_id ~ '^[a-z0-9][a-z0-9-]{1,63}$')
);

CREATE INDEX IF NOT EXISTS idx_leaderboard_club_aliases_club_id ON public.leaderboard_club_aliases (club_id);

