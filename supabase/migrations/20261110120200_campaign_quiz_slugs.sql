-- One registry of the public slug of every page in every language, so pages (also agent-made ones) get localized
-- URLs without a web release, and no two pages can claim the same URL. Backfilled with the slugs the web served until
-- now (its hardcoded tables); every other page/language keeps its source slug, exactly as before.
CREATE TABLE public.campaign_quiz_slugs (
  quiz_slug text NOT NULL REFERENCES public.campaign_quizzes(slug) ON DELETE CASCADE ON UPDATE CASCADE,
  locale text NOT NULL CHECK (locale IN ('en', 'ka', 'es', 'ru', 'pt', 'de', 'tr', 'fr')),
  public_slug text NOT NULL CHECK (char_length(public_slug) <= 80 AND public_slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (quiz_slug, locale),
  CONSTRAINT uq_campaign_quiz_slugs_public UNIQUE (locale, public_slug)
);

ALTER TABLE public.campaign_quiz_slugs ENABLE ROW LEVEL SECURITY;
REVOKE ALL PRIVILEGES ON TABLE public.campaign_quiz_slugs FROM PUBLIC, anon, authenticated;

