SELECT page.slug, locale.code, COALESCE(explicit.public_slug, page.slug)
FROM public.campaign_quizzes page
CROSS JOIN (VALUES ('en'), ('ka'), ('es'), ('ru'), ('pt'), ('de'), ('tr'), ('fr')) AS locale (code)
LEFT JOIN explicit ON explicit.quiz_slug = page.slug AND explicit.locale = locale.code;
